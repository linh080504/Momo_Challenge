BEGIN;

CREATE SCHEMA IF NOT EXISTS tkc;
REVOKE ALL ON SCHEMA tkc FROM PUBLIC;

CREATE TABLE IF NOT EXISTS tkc.campaigns (
    id varchar(32) PRIMARY KEY,
    state varchar(16) NOT NULL,
    "group" varchar(10),
    review_group varchar(10),
    risk varchar(10) NOT NULL,
    signals json NOT NULL,
    created integer NOT NULL,
    revision integer NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_campaigns_state ON tkc.campaigns (state);

CREATE TABLE IF NOT EXISTS tkc.reports (
    id varchar(64) PRIMARY KEY,
    reporter varchar(64) NOT NULL,
    campaign varchar(32) NOT NULL,
    created integer NOT NULL,
    snapshot json NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_reports_reporter ON tkc.reports (reporter);
CREATE INDEX IF NOT EXISTS ix_reports_campaign ON tkc.reports (campaign);

CREATE TABLE IF NOT EXISTS tkc.campaign_entities (
    campaign varchar(32) NOT NULL,
    digest varchar(64) NOT NULL,
    kind varchar(12) NOT NULL,
    PRIMARY KEY (campaign, digest)
);
CREATE INDEX IF NOT EXISTS ix_campaign_entities_digest ON tkc.campaign_entities (digest);

CREATE TABLE IF NOT EXISTS tkc.audit_log (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign varchar(32) NOT NULL,
    actor varchar(254) NOT NULL,
    action varchar(16) NOT NULL,
    created integer NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_audit_log_campaign ON tkc.audit_log (campaign);

CREATE TABLE IF NOT EXISTS tkc.sessions (
    digest varchar(64) PRIMARY KEY,
    email varchar(254) NOT NULL,
    role varchar(8) NOT NULL,
    expires integer NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_sessions_expires ON tkc.sessions (expires);

COMMIT;
