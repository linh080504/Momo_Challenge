BEGIN;

CREATE TABLE IF NOT EXISTS tkc.brand_cases (
    host varchar(253) PRIMARY KEY,
    state varchar(16) NOT NULL,
    revision integer NOT NULL,
    sources json NOT NULL,
    assessment json NOT NULL,
    created integer NOT NULL,
    updated integer NOT NULL,
    expires integer
);
CREATE INDEX IF NOT EXISTS ix_brand_cases_state ON tkc.brand_cases (state);

CREATE TABLE IF NOT EXISTS tkc.brand_decisions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host varchar(253) NOT NULL,
    revision integer NOT NULL,
    decision varchar(16) NOT NULL,
    actor varchar(254) NOT NULL,
    created integer NOT NULL,
    UNIQUE (host, revision)
);

COMMIT;
